import numpy as np
import pandas as pd
from datetime import datetime, timedelta
from typing import Dict, Any, List, Optional

class SyntheticRetentionSimulator:
    """
    Synthetic Retention Experiment Simulator.
    
    Generates realistic historical treatment vs control campaign datasets to demonstrate
    Uplift modeling, A/B testing evaluation, and ROI measurement.
    
    NOTE: All datasets generated by this module are clearly labeled as 
    'Simulation / Demonstration Data' to adhere to strict AI claims standards.
    """
    def __init__(self, seed: int = 42):
        self.seed = seed
        np.random.seed(seed)

    def generate_experiment_dataset(
        self,
        num_customers: int = 1000,
        control_ratio: float = 0.30,
        campaign_name: str = "Demo Retention Experiment Q3"
    ) -> pd.DataFrame:
        """
        Generate a synthetic dataset with customer demographics, treatment assignment,
        and simulated retention outcomes.
        """
        np.random.seed(self.seed)
        
        customer_ids = [f"CUST-{1000 + i}" for i in range(num_customers)]
        
        # Categorical choices matching Telco dataset
        contracts = np.random.choice(["Month-to-month", "One year", "Two year"], size=num_customers, p=[0.55, 0.25, 0.20])
        internet = np.random.choice(["Fiber optic", "DSL", "No"], size=num_customers, p=[0.45, 0.35, 0.20])
        tech_support = np.random.choice(["No", "Yes", "No internet service"], size=num_customers, p=[0.50, 0.30, 0.20])
        tenures = np.random.randint(1, 72, size=num_customers)
        monthly_charges = np.random.uniform(20.0, 118.0, size=num_customers)
        
        # Calculate baseline churn probability without intervention
        baseline_churn_prob = []
        for i in range(num_customers):
            c_factor = 0.35 if contracts[i] == "Month-to-month" else (0.15 if contracts[i] == "One year" else 0.05)
            i_factor = 0.20 if internet[i] == "Fiber optic" else 0.05
            t_factor = -0.15 if tech_support[i] == "Yes" else 0.05
            tenure_factor = -min(0.25, tenures[i] * 0.005)
            charge_factor = min(0.15, (monthly_charges[i] - 50) * 0.002)
            
            p_churn = 0.25 + c_factor + i_factor + t_factor + tenure_factor + charge_factor + np.random.normal(0, 0.05)
            baseline_churn_prob.append(float(np.clip(p_churn, 0.05, 0.95)))
            
        baseline_churn_prob = np.array(baseline_churn_prob)
        baseline_control_retention = 1.0 - baseline_churn_prob

        # Treatments
        treatments = ["CONTROL", "15% Retention Discount", "Free Technical Support", "Premium Plan Upgrade", "Loyalty Reward", "Priority Support"]
        treatment_probs = [control_ratio] + [(1.0 - control_ratio) / 5] * 5
        
        assigned_treatments = np.random.choice(treatments, size=num_customers, p=treatment_probs)
        
        # Calculate heterogeneous treatment uplift
        actual_uplifts = []
        outcomes_retained = []
        actual_costs = []
        
        cost_map = {
            "CONTROL": 0.0,
            "15% Retention Discount": 2000.0,
            "Free Technical Support": 500.0,
            "Premium Plan Upgrade": 1000.0,
            "Loyalty Reward": 800.0,
            "Priority Support": 1500.0
        }
        
        for i in range(num_customers):
            t = assigned_treatments[i]
            cost = cost_map[t]
            actual_costs.append(cost)
            
            if t == "CONTROL":
                uplift = 0.0
            elif t == "15% Retention Discount":
                uplift = 0.22 if contracts[i] == "Month-to-month" or monthly_charges[i] > 80 else 0.08
            elif t == "Free Technical Support":
                uplift = 0.26 if tech_support[i] == "No" or internet[i] == "Fiber optic" else 0.10
            elif t == "Premium Plan Upgrade":
                uplift = 0.18 if tenures[i] > 12 else 0.04
            elif t == "Loyalty Reward":
                uplift = 0.15 if tenures[i] >= 18 else -0.03 # Negative uplift for non-loyal!
            elif t == "Priority Support":
                uplift = 0.24 if monthly_charges[i] > 90 else 0.10
            else:
                uplift = 0.10

            # Add noise to treatment outcome
            uplift_noisy = uplift + np.random.normal(0, 0.02)
            actual_uplifts.append(float(uplift_noisy))
            
            # P(retained | treatment) = P(retained | control) + uplift
            p_retained_t = np.clip(baseline_control_retention[i] + uplift_noisy, 0.01, 0.99)
            retained = np.random.rand() < p_retained_t
            outcomes_retained.append(bool(retained))

        # Customer economic value
        gross_margin = 0.65
        lifetime_months = np.where(contracts == "Two year", 36, np.where(contracts == "One year", 24, 12))
        economic_values = monthly_charges * lifetime_months * gross_margin

        df = pd.DataFrame({
            "customer_id": customer_ids,
            "Contract": contracts,
            "InternetService": internet,
            "TechSupport": tech_support,
            "tenure": tenures,
            "MonthlyCharges": np.round(monthly_charges, 2),
            "baseline_churn_probability": np.round(baseline_churn_prob, 4),
            "customer_economic_value": np.round(economic_values, 2),
            "treatment": assigned_treatments,
            "intervention_cost": actual_costs,
            "simulated_uplift": np.round(actual_uplifts, 4),
            "retained": outcomes_retained,
            "churned": [not r for r in outcomes_retained],
            "campaign_id": "CMP-DEMO-001",
            "campaign_name": campaign_name,
            "is_synthetic": True,
            "data_label": "Simulation / Demonstration Data",
            "treatment_date": datetime.utcnow() - timedelta(days=45),
            "outcome_date": datetime.utcnow() - timedelta(days=15)
        })
        
        return df
